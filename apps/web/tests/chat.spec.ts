import { openChatSettings, expect, test, type Page } from './fixtures'
import AxeBuilder from '@axe-core/playwright'
import { mkdir } from 'node:fs/promises'

test.describe.configure({ mode: 'serial' })

async function connect(page: Page) {
  await expect(page.getByRole('button', { name: 'Codex Provider', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Auto Profile', exact: true })).toBeEnabled()
  if (!await page.getByRole('button', { name: 'Show chat history', exact: true }).isVisible())
    await expect(page.getByRole('button', { name: 'New project', exact: true })).toBeEnabled()
}
async function createProject(page: Page, name: string, path = '/tmp') {
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New project', exact: true })
  await dialog.getByLabel('Project name').fill(name)
  await dialog.getByLabel('Project path').fill(path)
  await dialog.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(dialog).toHaveCount(0)
}

test('Chat starts with empty history and no seeded projects or drafts', async ({ page }) => {
  await page.goto('/#/chat')
  await expect(page).toHaveURL(/#\/chat$/)
  await expect(page).toHaveTitle('Aixand · Chat')
  const navigation = page.getByRole('navigation', { name: 'Workspace navigation' })
  await expect(navigation.getByRole('link', { name: 'Chat', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Auto Profile', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Instructions', exact: true }).fill('Start automatically')
  await expect(page.getByRole('button', { name: 'Start agent', exact: true })).toBeEnabled()
  await page.getByRole('textbox', { name: 'Instructions', exact: true }).fill('')
  const history = page.getByRole('navigation', { name: 'Chat history', exact: true })
  await expect(history.getByRole('region', { name: 'Recent conversations', exact: true })).toContainText('Your conversations will appear here.')
  await expect(history.getByRole('region', { name: 'Recent conversations', exact: true }).getByRole('button')).toHaveCount(0)
  await expect(history.getByRole('region', { name: 'Projects', exact: true })).toContainText('Keep related conversations together.')
  await (await openChatSettings(page)).getByRole('button', { name: / Project$/ }).click()
  await expect(page.getByRole('option', { name: /^Aixand|^Studio website|^Developer tools/ })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.getByRole('dialog', { name: 'Chat settings', exact: true }).getByRole('button', { name: 'Close dialog', exact: true }).click()
  await expect(page.getByRole('button', { name: 'New project', exact: true })).toBeEnabled()
  await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('link', { name: 'Home', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Continue working', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'New chat', exact: true }).click()
  await expect(page).toHaveURL(/#\/chat$/)
})

test('new project needs only name and path, validates the directory, and survives reload', async ({ page }) => {
  await page.goto('/#/chat')
  await connect(page)
  await page.getByRole('textbox', { name: 'Instructions', exact: true }).fill('Keep these instructions')
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'New project', exact: true })
  await expect(dialog.getByLabel('Project name')).toBeFocused()
  await expect(dialog.getByRole('textbox')).toHaveCount(2)
  await expect(dialog.getByRole('button', { name: 'Create project', exact: true })).toBeDisabled()
  await dialog.getByLabel('Project name').fill('My workspace')
  await dialog.getByLabel('Project path').fill('/this-project-does-not-exist-aixand')
  await dialog.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('Project directory does not exist')
  await dialog.getByLabel('Project path').fill('/tmp')
  await dialog.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Instructions', exact: true })).toHaveValue('Keep these instructions')
  await expect(page.locator('.command-composer-options > .command-context-picker--project')).toContainText('My workspace')
  await expect(page.getByRole('region', { name: 'My workspace conversations', exact: true })).toContainText('No conversations yet.')
  await (await openChatSettings(page)).getByRole('button', { name: / Project$/ }).click()
  await expect(page.getByRole('option', { name: /^My workspace/ })).toContainText('/tmp')
  await page.keyboard.press('Escape')
  await page.reload()
  await connect(page)
  await page.getByRole('button', { name: 'My workspace, 0 conversations', exact: true }).click()
  await page.getByRole('button', { name: 'Start conversation', exact: true }).click()
  await expect(page.locator('.command-composer-options > .command-context-picker--project')).toContainText('My workspace')
  await expect(page.getByRole('heading', { name: 'What are we working on?', exact: true })).toBeVisible()
})

test('project picker changes context without losing instructions', async ({ page }, testInfo) => {
  await page.goto('/#/chat')
  await connect(page)
  const projectPath = testInfo.outputPath('review-project')
  await mkdir(projectPath, { recursive: true })
  await createProject(page, 'Review project', projectPath)
  await (await openChatSettings(page)).getByRole('button', { name: / Project$/ }).click()
  await page.getByRole('option', { name: 'New project…', exact: true }).click()
  const creation = page.getByRole('dialog', { name: 'New project', exact: true })
  await expect(creation).toBeVisible()
  await creation.getByRole('button', { name: 'Cancel', exact: true }).click()
  const input = page.getByRole('textbox', { name: 'Instructions', exact: true })
  await input.fill('Review the responsive layout')
  await (await openChatSettings(page)).getByRole('button', { name: / Project$/ }).click()
  await page.getByRole('option', { name: /^No project/ }).click()
  await expect(input).toHaveValue('Review the responsive layout')
  await expect(page.getByRole('button', { name: 'Start agent', exact: true })).toBeEnabled()
  await (await openChatSettings(page)).getByRole('button', { name: / Project$/ }).click()
  await page.getByRole('option', { name: /^Review project/ }).click()
  await expect(input).toHaveValue('Review the responsive layout')
  await expect(page.locator('.command-composer-options > .command-context-picker--project')).toContainText('Review project')
  await expect(page.getByRole('button', { name: 'Start agent', exact: true })).toBeEnabled()
})

test('project dialog, history, and picker work on mobile in light and dark themes', async ({ page }) => {
  for (const theme of ['light', 'dark']) {
    await page.addInitScript(value => localStorage.setItem('aixand.appearance', value), theme)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/#/chat')
    await page.reload()
    await connect(page)
    const trigger = page.getByRole('button', { name: 'Show chat history', exact: true })
    await trigger.click()
    await expect(page.getByRole('dialog', { name: 'Chat history' })).toBeVisible()
    await page.getByRole('button', { name: 'New project', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'New project', exact: true })
    const creation = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(creation.violations, `${theme} project creation`).toEqual([])
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('button', { name: 'New project', exact: true })).toBeFocused()
    await page.getByRole('button', { name: 'My workspace, 0 conversations', exact: true }).click()
    const detail = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(detail.violations, `${theme} project history`).toEqual([])
    await page.getByRole('button', { name: 'My workspace, 0 conversations', exact: true }).click()
    await expect(page.getByRole('button', { name: 'My workspace, 0 conversations', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await (await openChatSettings(page)).getByRole('button', { name: / Project$/ }).click()
    await expect(page.locator('.command-context-options')).toHaveCSS('opacity', '1')
    const picker = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(picker.violations, `${theme} project picker`).toEqual([])
    await page.keyboard.press('Escape')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `artifacts/projects-live/${theme}-mobile.png`, fullPage: true })
  }
})
